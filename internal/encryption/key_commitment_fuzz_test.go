// ---- GF(2^128) / GHASH, per NIST SP 800-38D ----

type gf128 struct{ hi, lo uint64 }

func gfFromBytes(b []byte) gf128 {
	return gf128{binary.BigEndian.Uint64(b[:8]), binary.BigEndian.Uint64(b[8:16])}
}

func (x gf128) bytes() []byte {
	out := make([]byte, 16)
	binary.BigEndian.PutUint64(out[:8], x.hi)
	binary.BigEndian.PutUint64(out[8:], x.lo)
	return out
}

func (x gf128) xor(y gf128) gf128 { return gf128{x.hi ^ y.hi, x.lo ^ y.lo} }

// gfOne is the multiplicative identity in GCM's bit order (bit 0 = MSB).
var gfOne = gf128{hi: 1 << 63}

func gfMul(x, y gf128) gf128 {
	var z gf128
	v := y
	for i := range 128 {
		var bit uint64
		if i < 64 {
			bit = (x.hi >> (63 - uint(i))) & 1
		} else {
			bit = (x.lo >> (127 - uint(i))) & 1
		}
		if bit == 1 {
			z = z.xor(v)
		}
		lsb := v.lo & 1
		v.lo = v.lo>>1 | v.hi<<63
		v.hi >>= 1
		if lsb == 1 {
			v.hi ^= 0xe1 << 56
		}
	}
	return z
}

// gfInv returns x^(2^128-2), the inverse of non-zero x.
func gfInv(x gf128) gf128 {
	res, sq := gfOne, x
	for i := 1; i < 128; i++ {
		sq = gfMul(sq, sq)
		res = gfMul(res, sq)
	}
	return res
}

func padTo16(b []byte) []byte {
	if r := len(b) % 16; r != 0 {
		b = append(append([]byte(nil), b...), make([]byte, 16-r)...)
	}
	return b
}

// ghashBlocks computes GHASH_h over aad||ct (each zero-padded) and the length block.
func ghashBlocks(h gf128, aad, ct []byte) gf128 {
	var y gf128
	for _, part := range [][]byte{padTo16(aad), padTo16(ct)} {
		for i := 0; i < len(part); i += 16 {
			y = gfMul(y.xor(gfFromBytes(part[i:i+16])), h)
		}
	}
	lens := make([]byte, 16)
	binary.BigEndian.PutUint64(lens[:8], uint64(len(aad))*8)
	binary.BigEndian.PutUint64(lens[8:], uint64(len(ct))*8)
	return gfMul(y.xor(gfFromBytes(lens)), h)
}

// gcmKeyParts returns H = E_K(0) and the tag mask E_K(nonce||0^31||1) for a 96-bit nonce.
func gcmKeyParts(key, nonce []byte) (h, mask gf128) {
	blk, err := aes.NewCipher(key)
	if err != nil {
		panic("aes.NewCipher: " + err.Error())
	}
	var zero, j0, out [16]byte
	blk.Encrypt(out[:], zero[:])
	h = gfFromBytes(out[:])
	copy(j0[:], nonce)
	j0[15] = 1
	blk.Encrypt(out[:], j0[:])
	return h, gfFromBytes(out[:])
}

// craftCollision builds ct (len(prefix)+16 bytes) and tag such that
// (nonce, ct, tag, aad) authenticates under both k1 and k2: the last ciphertext
// block is solved for in GF(2^128), the standard GCM key multi-collision.
// ok is false in the degenerate case H1^j == H2^j (negligible for random keys).
func craftCollision(k1, k2, nonce, aad, prefix []byte) (ct, tag []byte, ok bool) {
	h1, m1 := gcmKeyParts(k1, nonce)
	h2, m2 := gcmKeyParts(k2, nonce)
	zeroCT := append(append([]byte(nil), prefix...), make([]byte, 16)...)
	oneCT := append(append([]byte(nil), prefix...), gfOne.bytes()...)
	g1z, g2z := ghashBlocks(h1, aad, zeroCT), ghashBlocks(h2, aad, zeroCT)
	c1 := ghashBlocks(h1, aad, oneCT).xor(g1z) // coefficient of the free block under k1
	c2 := ghashBlocks(h2, aad, oneCT).xor(g2z)
	d := c1.xor(c2)
	if d == (gf128{}) {
		return nil, nil, false
	}
	x := g1z.xor(m1).xor(g2z).xor(m2)
	x = gfMul(x, gfInv(d))
	ct = append(append([]byte(nil), prefix...), x.bytes()...)
	return ct, ghashBlocks(h1, aad, ct).xor(m1).bytes(), true
}

// stdOpens opens (nonce, ct||tag) with crypto/cipher's stock GCM, independent of Keyorix.
func stdOpens(key, nonce, ct, tag, aad []byte) bool {
	blk, err := aes.NewCipher(key)
	if err != nil {
		panic("aes.NewCipher: " + err.Error())
	}
	g, err := cipher.NewGCM(blk)
	if err != nil {
		panic("cipher.NewGCM: " + err.Error())
	}
	_, err = g.Open(nil, nonce, append(append([]byte(nil), ct...), tag...), aad)
	return err == nil
}

func kcDerive32(seed []byte) []byte {
	k := make([]byte, 32)
	for i := range k {
		k[i] = 0x3d + byte(7*i)
	}
	for i, b := range seed {
		k[i%32] ^= b
	}
	return k
}

// kcKeyPair derives two distinct AES-256 keys from the fuzz seeds.
func kcKeyPair(s1, s2 []byte) (k1, k2 []byte) {
	k1, k2 = kcDerive32(s1), kcDerive32(append([]byte{0xa5}, s2...))
	if bytes.Equal(k1, k2) {
		k2[0] ^= 0xff
	}
	return k1, k2
}

// partitioned crafts the collision and asserts the harness itself is sound: the
// result must open under both keys with stock GCM, else it is a harness bug.
func partitioned(t testing.TB, k1, k2, nonce, aad, prefix []byte) (ct, tag []byte, ok bool) {
	ct, tag, ok = craftCollision(k1, k2, nonce, aad, prefix)
	if !ok {
		return nil, nil, false
	}
	if !stdOpens(k1, nonce, ct, tag, aad) || !stdOpens(k2, nonce, ct, tag, aad) {
		t.Fatalf("HARNESS BUG: crafted ciphertext does not open under both keys with stock crypto/cipher GCM (nonce=%x aad=%x prefixLen=%d)", nonce, aad, len(prefix))
	}
	return ct, tag, true
}

// kcSealer is one seal/open pair under a raw 32-byte key. The real pairs are the
// value AEAD and wrapKey/unwrapKey; the red-proof plants one that ignores the key.
type kcSealer struct {
	name string
	seal func(key, plaintext, aad []byte) []byte
	open func(key, sealed, aad []byte) ([]byte, error)
}

func kcRealSealers() []kcSealer {
	return []kcSealer{
		{
			name: "value AEAD (EncryptWithAAD/DecryptWithAAD)",
			seal: func(key, pt, aad []byte) []byte {
				svc, err := aead.NewEncryptionService(key)
				if err != nil {
					panic(err)
				}
				enc, err := svc.EncryptWithAAD(pt, "v1", aad)
				if err != nil {
					panic(err)
				}
				// Carry the nonce with the data so a single blob round-trips.
				n, _ := base64.StdEncoding.DecodeString(enc.Metadata.Nonce)
				return append(n, enc.Data...)
			},
			open: func(key, sealed, aad []byte) ([]byte, error) {
				svc, err := aead.NewEncryptionService(key)
				if err != nil {
					panic(err)
				}
				return svc.DecryptWithAAD(&aead.EncryptedData{
					Data: sealed[12:],
					Metadata: aead.EncryptionMetadata{
						Algorithm: aead.AESCipherSuite,
						Nonce:     base64.StdEncoding.EncodeToString(sealed[:12]),
					},
				}, aad)
			},
		},
		{
			name: "DEK wrap (wrapKey/unwrapKey)",
			seal: func(key, pt, _ []byte) []byte {
				w, err := wrapKey(pt, key)
				if err != nil {
					panic(err)
				}
				return w
			},
			open: func(key, sealed, _ []byte) ([]byte, error) { return unwrapKey(sealed, key) },
		},
	}
}

// kcDenyViolation returns a non-empty description when s breaks the deny
// direction (sealed under k1, must not open under k2 != k1) or the positive
// control (must open under k1).
func kcDenyViolation(s kcSealer, k1, k2, plaintext, aad []byte) string {
	sealed := s.seal(k1, plaintext, aad)
	if got, err := s.open(k1, sealed, aad); err != nil || !bytes.Equal(got, plaintext) {
		return s.name + ": positive control failed: does not round-trip under its own key"
	}
	if _, err := s.open(k2, sealed, aad); err == nil {
		return "KEY-COMMITMENT VIOLATION: " + s.name + ": sealed under K1, authenticated under K2 != K1"
	}
	return ""
}

func FuzzKeyCommitmentDeny(f *testing.F) {
	f.Add([]byte("k1"), []byte("k2"), []byte("secret value"), []byte("keyorix:v2:1:2:3"))
	f.Add([]byte{}, []byte{0}, []byte{}, []byte{})
	f.Add([]byte("same-prefix-a"), []byte("same-prefix-b"), bytes.Repeat([]byte{0x41}, 40), []byte("aad"))

	f.Fuzz(func(t *testing.T, s1, s2, plaintext, aad []byte) {
		fuzzutil.Guard(t.Fatalf, "key-commitment deny", func() {
			k1, k2 := kcKeyPair(s1, s2)
			for _, s := range kcRealSealers() {
				if v := kcDenyViolation(s, k1, k2, plaintext, aad); v != "" {
					panic(v)
				}
			}
		})
	})
}

// TestKeyCommitmentDeny_RedProof_PlantedKeylessAEAD shows the deny oracle fires:
// a planted AEAD whose open ignores the key (authenticates under any K2) must be
// reported, while both real sealers must not be.
func TestKeyCommitmentDeny_RedProof_PlantedKeylessAEAD(t *testing.T) {
	k1, k2 := kcKeyPair([]byte("a"), []byte("b"))
	planted := kcSealer{
		name: "planted keyless AEAD",
		seal: func(_, pt, _ []byte) []byte { return append([]byte(nil), pt...) },
		open: func(_, sealed, _ []byte) ([]byte, error) { return append([]byte(nil), sealed...), nil },
	}
	if v := kcDenyViolation(planted, k1, k2, []byte("pt"), nil); v == "" {
		t.Fatal("red-proof failed: the deny oracle did not fire on an AEAD with no key binding")
	}
	for _, s := range kcRealSealers() {
		if v := kcDenyViolation(s, k1, k2, []byte("pt"), []byte("aad")); v != "" {
			t.Fatalf("real sealer flagged: %s", v)
		}
	}
}

// FuzzKeyCommitmentPartition fuzzes the key pair, nonce, AAD and ciphertext
// prefix of the multi-collision. It asserts only what is sound: the construction
// is correct (stock GCM opens it under both keys; failure = harness bug) and the
// real paths never panic on it. What the real paths decide is pinned in
// TestKeyCommitment_PartitionedCiphertext_DocumentedGap.
func FuzzKeyCommitmentPartition(f *testing.F) {
	f.Add([]byte("k1"), []byte("k2"), []byte("0123456789ab"), []byte("keyorix:v2:1:2:3"), []byte{})
	f.Add([]byte{1}, []byte{2}, make([]byte, 12), []byte{}, bytes.Repeat([]byte{7}, 16))
	f.Add([]byte("a"), []byte("b"), []byte("nonce-nonce!"), []byte("0123456789abcdef-long-aad"), bytes.Repeat([]byte{9}, 32))

	f.Fuzz(func(t *testing.T, s1, s2, nonceSeed, aad, prefixSeed []byte) {
		fuzzutil.Guard(t.Fatalf, "key-commitment partition", func() {
			k1, k2 := kcKeyPair(s1, s2)
			nonce := make([]byte, 12)
			copy(nonce, nonceSeed)
			prefix := prefixSeed[:len(prefixSeed)/16*16]
			if len(prefix) > 64 {
				prefix = prefix[:64]
			}
			ct, tag, ok := partitioned(t, k1, k2, nonce, aad, prefix)
			if !ok {
				return
			}
			ed := &aead.EncryptedData{
				Data: append(append([]byte(nil), ct...), tag...),
				Metadata: aead.EncryptionMetadata{
					Algorithm: aead.AESCipherSuite,
					Nonce:     base64.StdEncoding.EncodeToString(nonce),
				},
			}
			for _, k := range [][]byte{k1, k2} {
				svc, err := aead.NewEncryptionService(k)
				if err != nil {
					panic(err)
				}
				_, _ = svc.DecryptWithAAD(ed, aad) // must not panic; the verdict is pinned elsewhere
			}
			_, _ = unwrapKey(append(append([]byte(nil), nonce...), ed.Data...), k1)
		})
	})
}

// TestKeyCommitment_PartitionedCiphertext_DocumentedGap pins what the real wrap
// and value paths do with a GHASH-partitioned ciphertext. It is a characterisation
// of a known defence-in-depth gap, not a claim that the behaviour is desirable.
func TestKeyCommitment_PartitionedCiphertext_DocumentedGap(t *testing.T) {
	k1, k2 := kcKeyPair([]byte("kek-one"), []byte("kek-two"))
	nonce := []byte("0123456789ab")
	aad := SecretAAD(1, 2, 3)
	prefix := bytes.Repeat([]byte{0x42}, 16) // 16 + 16 = 32 bytes: a DEK-sized plaintext

	ct, tag, ok := partitioned(t, k1, k2, nonce, aad, prefix)
	if !ok {
		t.Fatal("construction degenerate for the fixed test keys")
	}

	// (b1) DEK wrap path: wrapKey layout nonce||ct||tag, AAD nil, so craft with nil AAD.
	ct0, tag0, ok := partitioned(t, k1, k2, nonce, nil, prefix)
	if !ok {
		t.Fatal("construction degenerate (nil AAD)")
	}
	blob := append(append(append([]byte(nil), nonce...), ct0...), tag0...)
	dek1, err1 := unwrapKey(blob, k1)
	dek2, err2 := unwrapKey(blob, k2)
	if err1 != nil || err2 != nil {
		t.Fatalf("GAP CLOSED? unwrapKey now rejects a partitioned wrapped DEK (err under K1=%v, K2=%v): "+
			"flip this test to the deny direction and record the new binding in INVARIANTS", err1, err2)
	}
	if len(dek1) != 32 || len(dek2) != 32 || bytes.Equal(dek1, dek2) {
		t.Fatalf("expected two distinct 32-byte DEKs from one blob, got len %d/%d equal=%v", len(dek1), len(dek2), bytes.Equal(dek1, dek2))
	}
	// The stand-in check: the DEK epoch (HMAC fingerprint) tells the two apart.
	s1, _ := aead.NewEncryptionService(dek1)
	s2, _ := aead.NewEncryptionService(dek2)
	f1, e1 := s1.Fingerprint()
	f2, e2 := s2.Fingerprint()
	if e1 != nil || e2 != nil || f1 == f2 {
		t.Fatalf("DEK fingerprints must differ for the two unwrapped DEKs (%q vs %q, %v %v)", f1, f2, e1, e2)
	}

	// (b2) Value path with a secret-version AAD.
	ed := &aead.EncryptedData{
		Data: append(append([]byte(nil), ct...), tag...),
		Metadata: aead.EncryptionMetadata{
			Algorithm:  aead.AESCipherSuite,
			Nonce:      base64.StdEncoding.EncodeToString(nonce),
			AADVersion: "v2",
		},
	}
	v1, _ := aead.NewEncryptionService(k1)
	v2, _ := aead.NewEncryptionService(k2)
	_, eA := v1.DecryptWithAAD(ed, aad)
	_, eB := v2.DecryptWithAAD(ed, aad)
	if eA != nil || eB != nil {
		t.Fatalf("GAP CLOSED? DecryptWithAAD now rejects a partitioned value (K1 err=%v, K2 err=%v): flip to the deny direction", eA, eB)
	}
	// Binding that does hold: the same ciphertext under another row's AAD is refused.
	if _, err := v1.DecryptWithAAD(ed, SecretAAD(9, 9, 9)); err == nil {
		t.Fatal("a different secret/project/version AAD must not authenticate the partitioned value")
	}
}

// TestKeyCommitment_NoKeyIDOrVersionBinding pins (c): the wrapped DEK carries no key
// id/version and the stored key_version is outside the authenticated data.
func TestKeyCommitment_NoKeyIDOrVersionBinding(t *testing.T) {
	kek, _ := kcKeyPair([]byte("a"), []byte("b"))
	dek := bytes.Repeat([]byte{0x11}, 32)
	wrapped, err := wrapKey(dek, kek)
	if err != nil {
		t.Fatal(err)
	}
	if want := wrappedKeyNonceSize + len(dek) + 16; len(wrapped) != want {
		t.Fatalf("wrapped DEK is %d bytes, want exactly nonce+dek+tag = %d: a longer blob would mean a key id/version field was added; bind it and update this test", len(wrapped), want)
	}

	svc, err := aead.NewEncryptionService(dek)
	if err != nil {
		t.Fatal(err)
	}
	enc, err := svc.EncryptWithAAD([]byte("v"), "v1700000000", SecretAAD(1, 1, 1))
	if err != nil {
		t.Fatal(err)
	}
	enc.Metadata.KeyVersion = "v-attacker-chosen"
	if _, err := svc.DecryptWithAAD(enc, SecretAAD(1, 1, 1)); err != nil {
		t.Fatalf("GAP CLOSED? Metadata.KeyVersion is now authenticated (%v): flip this test to the deny direction", err)
	}
}
