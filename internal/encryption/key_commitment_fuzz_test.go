// key_commitment_fuzz_test.go -- KEYCOMMIT-1: key-commitment invariant for the
// KEK->DEK wrap (wrapKey/unwrapKey) and the secret AEAD (aead.EncryptionService).
//
// AES-GCM, including cipher.NewGCMWithRandomNonce which both paths use, is not
// key-committing: for two keys the attacker knows, one (nonce, ciphertext, tag)
// can authenticate under both (partitioning-oracle / "invisible salamanders",
// Len-Grubbs-Ristenpart 2021, Albertini et al. 2022). Neither seal site binds a
// key id, key version or key fingerprint, so the property is NOT enforced by the
// primitive layer; what limits impact is who can choose the keys (see the
// reachability notes below).
//
// Seal/open sites (inventory, KEYCOMMIT-1 task step 1). Established with
//
//	rg -n 'NewGCM|NewGCMWithRandomNonce|chacha20poly1305\.New|cipher\.AEAD|\.Seal\(nil|gcm\.Open' \
//	  -g '*.go' -g '!*_test.go' .
//
// (non-test Go only, comments and docs ignored); every hit is one of these sites:
//
//	wrapKey/unwrapKey (keymanager_lifecycle.go)  key = KEK (provider: passphrase PBKDF2,
//	  file, env, KMS, Shamir); nonce = random, prepended; AAD = nil; plaintext = 32-byte
//	  DEK; output nonce(12)||ct(32)||tag(16) -- no room for a key id or version.
//	aead.EncryptionService.{Encrypt,EncryptWithAAD} (aead/aead.go) key = DEK; nonce random
//	  (stored in Metadata.Nonce); AAD = ports.SecretAAD(secretID, projectID, version) for
//	  secret versions, user id for MFA/API/reset tokens, config/lease id for dynamic
//	  secrets, channel id for notification URLs, stream+index+total for chunks. AAD binds
//	  the row identity; it never binds a key id, key version (Metadata.KeyVersion is
//	  unauthenticated) or tenant other than the project id inside SecretAAD.
//	pqwrap keyset v1 (internal/pqwrap/keyset.go sealKEKSlot/OpenKeyset): KEK-slot AAD =
//	  header (magic, version, DEK KCV, slot count) || slot index. The kek_id is stored in
//	  front of the slot, not in the AAD; what commits a keyset to its keys is the
//	  HMAC-SHA256 over header||slots under an HKDF of the KEK and the DEK KCV check, both
//	  run by OpenKeyset after the GCM open. Not exercised here (separate package).
//	pqwrap legacy-60 (keyset.go openLegacy/SealLegacy): the wrapKey layout, AAD = nil, no
//	  key id, MAC or KCV: the same gap as wrapKey. pqwrap has no production importer
//	  today (only its own tests); not exercised here.
//	pqwrap hybrid envelope (pqwrap.go seal/Wrap, randomNonceGCM): wrap key derived per
//	  envelope from X25519+ML-KEM; AAD = envelope header (magic, version, suite,
//	  purpose, recipient key id) || caller context, so the recipient key id IS bound. Like
//	  any public-key wrap it has no sender authentication (pqwrap.go Wrap doc).
//	  Not exercised here.
//	CLI encrypted export (cli/cmd/secret_export_encrypt.go encryptExport/decryptExport,
//	  reached by `secret export --encrypt-to` and `secret import --decrypt-with`):
//	  AES-256-GCM, AAD = nil, under a random 32-byte key carried RSA-OAEP-wrapped in the
//	  envelope. Not key-committing either, but an envelope carries exactly one wrapped
//	  key, and anyone who can build an envelope for the recipient's public key can
//	  already encrypt any plaintext to it (no sender authentication), so a ciphertext
//	  that opens under two keys gives an attacker nothing extra. Not exercised here.
//
// Who chooses keys: the KEK comes from the operator's KeyProvider (passphrase,
// key file, env, KMS, Shamir shares); the DEK is generated by the server
// (GenerateRandomKey) and only ever leaves memory wrapped under that KEK. To craft
// a colliding ciphertext an attacker needs both keys, or a set of candidate keys
// (for example a passphrase dictionary plus the PBKDF2 salt) together with an
// open/fail oracle that tries blobs they submit under the real key (the
// partitioning-oracle setting). Neither exists below instance admin today: the KEK
// is the operator's, and the only paths that unwrap a key file (startup, restore)
// are operator-run, so no remote party can submit a wrapped blob and learn whether
// it opened. A future endpoint that unwraps or restores caller-supplied key
// material would be such an oracle and re-opens this analysis. Substituting one's
// own KEK and dek.key needs write access to the key directory or the restore
// command, i.e. instance admin or host root.
// Backup restore unwraps the archive's key files with the operator's own KEK
// (restore.go stageKeyFilesForKEKUnwrap). On PostgreSQL deployments only
// (dekEpochApplies is false on SQLite), the cross-replica DEK epoch check
// (dek_epoch.go) also compares the unwrapped DEK's HMAC fingerprint with the
// database; the two DEKs of a partitioned blob have different fingerprints
// (asserted below, true by construction for two different DEKs; the check itself
// is not run). The verdict rests on the KEK requirement, not on the epoch check:
// a defence-in-depth gap, not a vulnerability reachable below instance admin.
//
// What this file verifies:
//   - deny direction (FuzzKeyCommitmentDeny): a ciphertext sealed under K1 never
//     authenticates under K2 != K1, for the real wrapKey/unwrapKey and the real
//     EncryptWithAAD/DecryptWithAAD paths (the positive control K1 must open).
//     AES-GCM gives this by construction; the target is a regression guard for a
//     change of primitive or wrapper, not a search for a GCM weakness.
//   - the GHASH key-multi-collision construction is implemented correctly: the
//     crafted (nonce, ciphertext, tag) opens under BOTH keys with crypto/cipher's
//     stock GCM before it is shown to Keyorix (a failure there is a harness bug).
//   - FuzzKeyCommitmentPartition also crafts a nil-AAD collision for the fuzzed
//     keys and nonce and checks that the real unwrapKey opens it under both keys
//     to two distinct 32-byte DEKs (the DocumentedGap pin, over many key pairs).
//   - TestKeyCommitment_PartitionedCiphertext_DocumentedGap pins what Keyorix's
//     real paths do with that ciphertext TODAY: they accept it under both keys
//     (no key id/AAD/extra check at the primitive layer), the two unwrapped DEKs
//     differ, and so do their fingerprints (the value the PostgreSQL-only DEK
//     epoch check compares). If a key-committing check is added, this test goes
//     red on purpose: flip it to the deny direction.
//   - the wrapped DEK has no room for a key id/version, and Metadata.KeyVersion is
//     not authenticated (pinned, same flip-on-fix rule).
//
// KEYCOMMIT-2 adds: oracle (b) as the function kcPartitionViolation (the fuzz target
// and TestKeyCommitmentPartition_RedProof call the same code; the red-proof plants a
// keyless AEAD and a key-committing AEAD and runs a stock-GCM control);
// key_commitment_pqwrap_test.go (pqwrap keyset v1 KEK slot);
// key_commitment_epoch_db_test.go (the DEK epoch check against a real database).
//
// What this does NOT verify: reachability on a live path (that is argued above and
// in the PR, not tested), pqwrap legacy-60, the CLI encrypted export, KMS-wrapped
// KEK blobs (see the provider packages' *_key_binding_test.go), multi-block
// AAD/plaintext cases beyond the fuzzed prefix, or non-12-byte nonces (the real
// paths reject those).
