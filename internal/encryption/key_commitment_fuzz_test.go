// key_commitment_fuzz_test.go -- KEYCOMMIT-1: key-commitment invariant for the
// KEK->DEK wrap (wrapKey/unwrapKey) and the secret AEAD (aead.EncryptionService).
//
// AES-GCM, including cipher.NewGCMWithRandomNonce which both paths use, is not
// key-committing: for two keys the attacker knows, one (nonce, ciphertext, tag)
// can authenticate under both (partitioning-oracle / "invisible salamanders",
// Len-Grubbs-Ristenpart 2021, Albertini et al. 2022). Neither seal site binds a
// key id, key version or key fingerprint, so the property is NOT enforced by the
// primitive layer; what limits impact is who can choose the keys (see the
// reachability notes below).
//
// Seal/open sites (inventory, KEYCOMMIT-1 task step 1):
//
//	wrapKey/unwrapKey (keymanager_lifecycle.go)  key = KEK (provider: passphrase PBKDF2,
//	  file, env, KMS, Shamir); nonce = random, prepended; AAD = nil; plaintext = 32-byte
//	  DEK; output nonce(12)||ct(32)||tag(16) -- no room for a key id or version.
//	aead.EncryptionService.{Encrypt,EncryptWithAAD} key = DEK; nonce random (stored in
//	  Metadata.Nonce); AAD = ports.SecretAAD(secretID, projectID, version) for secret
//	  versions, user id for MFA/API/reset tokens, config/lease id for dynamic secrets,
//	  channel id for notification URLs, stream+index+total for chunks. AAD binds the
//	  row identity; it never binds a key id, key version (Metadata.KeyVersion is
//	  unauthenticated) or tenant other than the project id inside SecretAAD.
//	pqwrap (internal/pqwrap): hybrid KEK-slot wrap, AAD = header||slot index. Out of
//	  scope here (separate package); its slot AAD binds a kek_id, so it is the only
//	  site with a key identifier in the AAD.
//
// Who chooses keys: the KEK comes from the operator's KeyProvider (passphrase,
// key file, env, KMS, Shamir shares); the DEK is generated by the server
// (GenerateRandomKey) and only ever leaves memory wrapped under that KEK. An
// attacker needs to KNOW both keys to craft a colliding ciphertext, so the
// construction needs a party who already holds the operator's KEK (or can
// substitute their own KEK and dek.key, i.e. someone with write access to the
// key directory / the restore command, which is instance-admin or host root).
// Backup restore unwraps the archive's key files with the operator's own KEK
// (restore.go stageKeyFilesForKEKUnwrap) and the cross-replica DEK epoch check
// (dek_epoch.go) compares the unwrapped DEK's HMAC fingerprint with the database,
// which a partitioned wrapped DEK fails (asserted below). Verdict: a
// defence-in-depth gap, not a vulnerability reachable below instance admin.
//
// What this file verifies:
//   - deny direction (FuzzKeyCommitmentDeny): a ciphertext sealed under K1 never
//     authenticates under K2 != K1, for the real wrapKey/unwrapKey and the real
//     EncryptWithAAD/DecryptWithAAD paths (the positive control K1 must open).
//   - the GHASH key-multi-collision construction is implemented correctly: the
//     crafted (nonce, ciphertext, tag) opens under BOTH keys with crypto/cipher's
//     stock GCM before it is shown to Keyorix (a failure there is a harness bug).
//   - TestKeyCommitment_PartitionedCiphertext_DocumentedGap pins what Keyorix's
//     real paths do with that ciphertext TODAY: they accept it under both keys
//     (no key id/AAD/extra check at the primitive layer), the two unwrapped DEKs
//     differ, and their fingerprints (the DEK epoch) differ, so the epoch guard
//     is the extra check that stands in the way. If a key-committing check is
//     added, this test goes red on purpose: flip it to the deny direction.
//   - the wrapped DEK has no room for a key id/version, and Metadata.KeyVersion is
//     not authenticated (pinned, same flip-on-fix rule).
//
// What this does NOT verify: reachability on a live path (that is argued above and
// in the PR, not tested), pqwrap, KMS-wrapped KEK blobs, the DEK epoch guard
// itself against a database (only that the fingerprints differ), multi-block
// AAD/plaintext cases beyond the fuzzed prefix, or non-12-byte nonces (the real
// paths reject those).
