package libconformance

import (
	"testing"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/structpb"

	"github.com/keyorixhq/keyorix/internal/fuzzutil/complexity"
	"github.com/keyorixhq/keyorix/internal/fuzzutil/grammar"
)

// FuzzProtobufGrammarComplexity is a cost-per-byte oracle over the
// google.golang.org/protobuf runtime's wire decoder, fed by the grammar
// package's structure-aware protobuf generator instead of raw bytes.
//
// Companion to FuzzProtobufDecodeComplexity (which feeds raw bytes): where that
// target notes that "most fields land in the UNKNOWN-field set" because raw
// mutation rarely produces schema-matching wire, this target uses
// grammar.DecodeProto to give the fuzzer single-choice access to the structural
// shapes that raw mutation cannot reliably reach:
//   - packed repeated fields (a single LenDel field whose payload is many
//     concatenated varints — a flat allocation path the recursion limit does not
//     bound)
//   - deep nested messages (the recursion-limit path, up to 10000+ levels)
//   - non-minimal varints (extra continuation bytes in every tag and value)
//   - group-encoded fields (deprecated wire types 3+4, rarely generated by chance)
//   - wide flat messages (many fields with the same field number)
//
// The oracle property is identical to FuzzProtobufDecodeComplexity: decoding N
// GRAMMAR bytes must allocate O(N). The grammar bytes encode structural choices,
// not the raw wire bytes, so the budget is against the grammar input length, not
// the encoded wire length (which may be larger due to deep chains). The budget
// constants are set generously to account for chain expansion.
//
// What this oracle does NOT verify:
//   - Correctness of the decoded message's field values (only allocation cost).
//   - Mutation-flagged inputs (WrongWireType, OverlongVarint, LenDelta) that
//     proto.Unmarshal rejects — errors are discarded here, same as the sibling.
//   - Anything about gRPC authorisation or Keyorix business logic.
//   - CPU-only blow-up (only allocated bytes; CPU is guarded by MaxWall in the
//     guard package, not used here as that is the sibling target's concern).
func FuzzProtobufGrammarComplexity(f *testing.F) {
	// Seeds are grammar-encoded control bytes decoded by grammar.DecodeProto,
	// not raw protobuf wire bytes.
	f.Add([]byte{0x00})                   // minimal random tree
	f.Add([]byte{0x01, 0x00, 0x20})       // deep chain, modest depth
	f.Add([]byte{0x01, 0x10, 0x00})       // deep chain, large depth (nesting lever)
	f.Add([]byte{0x02, 0x04, 0x00})       // wide packed field, 4 values
	f.Add([]byte{0x02, 0x00, 0x10})       // wide packed field, 16 values
	f.Add([]byte{0x00, 0x03, 0x08, 0x01}) // random tree, field 1 varint

	budget := complexity.Budget{
		MaxAllocBytesPerByte: 512, // deep chains expand; grammar bytes are compact
		FloorBytes:           2 << 20,
		AbsMaxAllocBytes:     256 << 20, // matches the sibling's worst-case ceiling
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		msg := grammar.DecodeProto(data)
		wire := msg.Encode()

		n := len(data) // budget is against grammar input, not expanded wire
		c := complexity.Measure(func() {
			m := &structpb.Struct{}
			_ = proto.Unmarshal(wire, m) // result/err discarded; cost is the property
		})
		budget.Check(t.Fatalf, "proto.Unmarshal(grammar-built wire)", n, c)
	})
}
