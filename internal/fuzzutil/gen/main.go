// Command gen generates internal/fuzzutil/stateedge_gen.go: a switch with K
// distinct case bodies, each invoking its own //go:noinline no-op function.
// The point is that a coverage-instrumented build (go test -fuzz) sees K
// genuinely separate control-flow edges -- one per case -- so that calling
// StateEdge with a previously-unseen key looks like new coverage to Go's
// fuzzer, even when every other edge the input exercises has already been
// seen. See internal/fuzzutil/stateedge.go for the exported API.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
)

func main() {
	k := flag.Int("k", 2048, "number of distinct StateEdge cases to generate")
	out := flag.String("out", "stateedge_gen.go", "output file path")
	flag.Parse()

	if *k <= 0 {
		fmt.Fprintln(os.Stderr, "gen: -k must be positive")
		os.Exit(1)
	}

	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by internal/fuzzutil/gen; DO NOT EDIT.")
	fmt.Fprintln(&buf, "//go:generate go run ./gen -k", *k, "-out stateedge_gen.go")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "package fuzzutil")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "// stateEdgeK is the compile-time twin of the exported StateEdgeK: the number")
	fmt.Fprintln(&buf, "// of distinct cases stateEdgeSwitch dispatches through.")
	fmt.Fprintf(&buf, "const stateEdgeK = %d\n\n", *k)

	fmt.Fprintln(&buf, "// stateEdgeSwitch dispatches key to its own case -- each case's callee is a")
	fmt.Fprintln(&buf, "// distinct //go:noinline function, so each case is a distinct instrumented")
	fmt.Fprintln(&buf, "// coverage edge. A key with no matching case (>= stateEdgeK) is a no-op here;")
	fmt.Fprintln(&buf, "// StateEdge itself rejects such a key before calling in, loudly.")
	fmt.Fprintln(&buf, "func stateEdgeSwitch(key uint32) {")
	fmt.Fprintln(&buf, "\tswitch key {")
	for i := 0; i < *k; i++ {
		fmt.Fprintf(&buf, "\tcase %d:\n\t\tstateEdgeCase%d()\n", i, i)
	}
	fmt.Fprintln(&buf, "\t}")
	fmt.Fprintln(&buf, "}")
	fmt.Fprintln(&buf)

	for i := 0; i < *k; i++ {
		fmt.Fprintf(&buf, "//go:noinline\nfunc stateEdgeCase%d() {}\n\n", i)
	}

	fmt.Fprintln(&buf, "// stateEdgeCaseFuncs lists every case callee in dispatch order -- test-only")
	fmt.Fprintln(&buf, "// scaffolding so a unit test can confirm each key's case is a genuinely")
	fmt.Fprintln(&buf, "// distinct function (by pointer identity) rather than trusting the switch")
	fmt.Fprintln(&buf, "// above was generated correctly.")
	fmt.Fprintln(&buf, "var stateEdgeCaseFuncs = [stateEdgeK]func(){")
	for i := 0; i < *k; i++ {
		fmt.Fprintf(&buf, "\tstateEdgeCase%d,\n", i)
	}
	fmt.Fprintln(&buf, "}")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen: format:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen: write:", err)
		os.Exit(1)
	}
}
