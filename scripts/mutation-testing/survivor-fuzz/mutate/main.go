// Command mutate applies ONE gremlins-style mutation to a Go source file, or
// describes the node a gremlins position points at.
//
// gremlins reports a surviving mutant as "<TYPE> <file>:<line>:<col>". It has
// no "apply this one mutant" command, so the survivor-fuzz tooling re-creates
// the mutation here, for the operator kinds gremlins uses:
//
//	CONDITIONALS_BOUNDARY   <  <->  <=      >  <->  >=
//	CONDITIONALS_NEGATION   == <-> !=   <  ->  >=   <= -> >    >  -> <=   >= -> <
//	INCREMENT_DECREMENT     ++ <-> --
//	ARITHMETIC_BASE         +  <->  -       *  <->  /     %  -> *
//	INVERT_NEGATIVES        -x  ->  +x  (identity on the operand)
//
// Usage:
//
//	mutate -file F -line L -col C -type T            # describe (prints func, op)
//	mutate -file F -line L -col C -type T -out G     # write mutated copy to G
//
// The column gremlins reports is matched against the operator token, the start
// of the binary expression, or its left operand, whichever lines up; the tool
// refuses to mutate if no node matches (prints "no-node", exit 3).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

func main() {
	file := flag.String("file", "", "Go source file")
	line := flag.Int("line", 0, "line")
	col := flag.Int("col", 0, "column (1-based, bytes)")
	typ := flag.String("type", "", "gremlins mutation type")
	out := flag.String("out", "", "write mutated source here (omit to only describe)")
	clone := flag.String("clone", "", "write a _test.go file holding ONLY the mutated enclosing function, renamed <Name>__mut (same package, so it can reach unexported helpers)")
	flag.Parse()
	if *file == "" || *line == 0 || *typ == "" {
		fmt.Fprintln(os.Stderr, "usage: mutate -file F -line L -col C -type T [-out G]")
		os.Exit(2)
	}
	src, err := os.ReadFile(*file)
	if err != nil {
		fatal(err)
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, *file, src, parser.ParseComments)
	if err != nil {
		fatal(err)
	}
	pos := func(p token.Pos) (int, int) { q := fset.Position(p); return q.Line, q.Column }

	var found ast.Node
	var fn, enclosing string
	var encl *ast.FuncDecl
	var enclDecl *ast.FuncDecl
	ast.Inspect(f, func(n ast.Node) bool {
		if n == nil || found != nil {
			return false
		}
		if d, ok := n.(*ast.FuncDecl); ok {
			enclDecl = d
			enclosing = d.Name.Name
			if d.Recv != nil && len(d.Recv.List) == 1 {
				enclosing = "(" + exprStr(d.Recv.List[0].Type) + ")." + d.Name.Name
			}
		}
		switch x := n.(type) {
		case *ast.BinaryExpr:
			ol, oc := pos(x.OpPos)
			sl, sc := pos(x.Pos())
			xl, xc := pos(x.X.Pos())
			if (ol == *line && oc == *col) || (sl == *line && sc == *col) || (xl == *line && xc == *col) {
				if opFor(*typ, x.Op) != token.ILLEGAL {
					found, fn, encl = x, enclosing, enclDecl
				}
			}
		case *ast.IncDecStmt:
			l, c := pos(x.TokPos)
			sl, sc := pos(x.Pos())
			if (l == *line && c == *col) || (sl == *line && sc == *col) {
				found, fn, encl = x, enclosing, enclDecl
			}
		case *ast.UnaryExpr:
			l, c := pos(x.OpPos)
			if l == *line && c == *col && x.Op == token.SUB && *typ == "INVERT_NEGATIVES" {
				found, fn, encl = x, enclosing, enclDecl
			}
		}
		return true
	})
	if found == nil {
		fmt.Println("no-node")
		os.Exit(3)
	}
	desc := ""
	switch x := found.(type) {
	case *ast.BinaryExpr:
		nop := opFor(*typ, x.Op)
		desc = fmt.Sprintf("%s: %s %s %s -> %s", fn, exprStr(x.X), x.Op, exprStr(x.Y), nop)
		if *out != "" || *clone != "" {
			x.Op = nop
		}
	case *ast.IncDecStmt:
		nt := token.DEC
		if x.Tok == token.DEC {
			nt = token.INC
		}
		desc = fmt.Sprintf("%s: %s%s -> %s%s", fn, exprStr(x.X), x.Tok, exprStr(x.X), nt)
		if *out != "" || *clone != "" {
			x.Tok = nt
		}
	case *ast.UnaryExpr:
		desc = fmt.Sprintf("%s: -%s -> +%s", fn, exprStr(x.X), exprStr(x.X))
		if *out != "" || *clone != "" {
			x.Op = token.ADD
		}
	}
	fmt.Println(desc)
	if *clone != "" {
		encl.Doc = nil
		encl.Name = ast.NewIdent(encl.Name.Name + "__mut")
		var imports []ast.Decl
		for _, d := range f.Decls {
			if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
				imports = append(imports, g)
			}
		}
		cf := &ast.File{Name: f.Name, Decls: append(imports, encl)}
		var buf bytes.Buffer
		buf.WriteString("// Code generated by survivor-fuzz/mutate; DO NOT EDIT. A mutated clone of one function.\n\n")
		if err := format.Node(&buf, token.NewFileSet(), cf); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(*clone, buf.Bytes(), 0o600); err != nil {
			fatal(err)
		}
	}
	if *out != "" {
		var buf bytes.Buffer
		if err := format.Node(&buf, fset, f); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(*out, buf.Bytes(), 0o600); err != nil {
			fatal(err)
		}
	}
}

func opFor(typ string, op token.Token) token.Token {
	switch typ {
	case "CONDITIONALS_BOUNDARY":
		switch op {
		case token.LSS:
			return token.LEQ
		case token.LEQ:
			return token.LSS
		case token.GTR:
			return token.GEQ
		case token.GEQ:
			return token.GTR
		}
	case "CONDITIONALS_NEGATION":
		switch op {
		case token.EQL:
			return token.NEQ
		case token.NEQ:
			return token.EQL
		case token.LSS:
			return token.GEQ
		case token.LEQ:
			return token.GTR
		case token.GTR:
			return token.LEQ
		case token.GEQ:
			return token.LSS
		}
	case "ARITHMETIC_BASE":
		switch op {
		case token.ADD:
			return token.SUB
		case token.SUB:
			return token.ADD
		case token.MUL:
			return token.QUO
		case token.QUO:
			return token.MUL
		case token.REM:
			return token.MUL
		}
	}
	return token.ILLEGAL
}

func exprStr(e ast.Expr) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, token.NewFileSet(), e); err != nil {
		return "?"
	}
	s := strings.ReplaceAll(buf.String(), "\n", " ")
	if len(s) > 60 {
		s = s[:57] + "..."
	}
	return s
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "mutate:", err)
	os.Exit(1)
}
