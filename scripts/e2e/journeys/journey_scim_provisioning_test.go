// scimJourneyNoMFAReason: this journey drives /scim/v2 with the SCIM bearer token and reads
// the audit log as a plain-password admin; it tests no MFA configuration.
const scimJourneyNoMFAReason = "SCIM provisioning journey authenticates with the SCIM token and one plain-password admin; MFA enrolment is driven by journeys 18/19"

// scimJSON is a SCIM resource or list as far as this journey reads one.
type scimJSON struct {
	ID           string `json:"id"`
	UserName     string `json:"userName"`
	Active       bool   `json:"active"`
	TotalResults int    `json:"totalResults"`
	Resources    []struct {
		ID string `json:"id"`
	} `json:"Resources"`
	Members []struct {
		Value string `json:"value"`
	} `json:"members"`
}

func (s scimJSON) memberValues() []string {
	out := make([]string, 0, len(s.Members))
	for _, m := range s.Members {
		out = append(out, m.Value)
	}
	return out
}

// TestJourney_SCIMProvisioning is an IdP's directory sync against a real server, and what the
// operator sees afterwards. The SCIM token is generated by the harness and given to the server
// through KEYORIX_SCIM_TOKEN: SCIM has no token-issuance command or API.
//
//  1. the IdP provisions a user, reads it, finds it by userName, and deactivates it;
//  2. the deactivated user's personal access token stops working at once, and reactivating the
//     user does not hand it back (#3419);
//  3. the IdP provisions a group around the user, replaces its members (PUT), patches them
//     (add, remove), and the native group (admin API) shows the same members after each step;
//  4. the IdP deprovisions the group and the user, and each is gone for the admin too;
//  5. the admin audit log holds the scim.* rows, attributed to the SCIM principal ("system"),
//     and none of them contains the SCIM token.
//
// Not driven here: how a SCIM user obtains a PAT. SCIM accounts have no usable password
// (their first login is through the IdP, and `reissue-one-time-password` refuses them), and the
// SSO journey needs a Keycloak container. The token row is therefore written to the SQLite
// database directly, shaped exactly like a minted one (SHA-256 of the raw token); everything
// after that is the server's own behaviour.
func TestJourney_SCIMProvisioning(t *testing.T) {
	serverBin, _ := harness.BuildBinaries(t)
	s := harness.StartServer(t, serverBin, harness.DBBackend{
		Name: "sqlite-scim", NoMFAReason: scimJourneyNoMFAReason, EnableSCIM: true,
	})
	t.Cleanup(s.Close)
	if s.SCIMToken == "" {
		t.Fatal("the harness started the server without a SCIM token")
	}
	adminToken := adminLogin(t, s, "smoketestadmin", harness.BootstrapAdminPassword)

	scim := func(method, path string, body any, want int) scimJSON {
		t.Helper()
		env := restCall(t, s, s.SCIMToken, method, path, body)
		if env.StatusCode != want {
			t.Fatalf("SCIM %s %s: want HTTP %d, got %d: %s", method, path, want, env.StatusCode, env.Raw)
		}
		var out scimJSON
		if len(env.Raw) > 0 {
			if err := json.Unmarshal(env.Raw, &out); err != nil {
				t.Fatalf("SCIM %s %s: decode: %v\n%s", method, path, err, env.Raw)
			}
		}
		return out
	}
	// nativeMembers returns the user ids the admin API lists for a group.
	nativeMembers := func(groupID string) []string {
		t.Helper()
		env := restExpect(t, s, adminToken, http.MethodGet, "/api/v1/groups/"+groupID+"/members", nil, http.StatusOK)
		var data struct {
			Members []struct {
				ID uint `json:"id"`
			} `json:"members"`
		}
		if err := json.Unmarshal(env.Data, &data); err != nil {
			t.Fatalf("decode native group members: %v\n%s", err, env.Raw)
		}
		out := make([]string, 0, len(data.Members))
		for _, m := range data.Members {
			out = append(out, strconv.FormatUint(uint64(m.ID), 10))
		}
		return out
	}
	wantMembers := func(what, groupID string, scimView scimJSON, want ...string) {
		t.Helper()
		if got := scimView.memberValues(); !sameStrings(got, want) {
			t.Fatalf("%s: SCIM members = %v, want %v", what, got, want)
		}
		if got := nativeMembers(groupID); !sameStrings(got, want) {
			t.Fatalf("%s: the admin API lists members %v, want %v (SCIM and native group must agree)", what, got, want)
		}
	}

	// ── 1. provision, read, find, deactivate ──────────────────────────────────────
	const email = "scim-journey-user@example.invalid"
	user := scim(http.MethodPost, "/scim/v2/Users", map[string]any{
		"userName": email, "externalId": "idp|scim-journey-user", "displayName": "SCIM Journey User", "active": true,
		"emails": []map[string]any{{"value": email, "primary": true}},
	}, http.StatusCreated)
	if user.ID == "" || !user.Active {
		t.Fatalf("provisioned user: want an id and active=true, got %+v", user)
	}
	userPath := "/scim/v2/Users/" + user.ID
	if got := scim(http.MethodGet, userPath, nil, http.StatusOK); got.ID != user.ID || got.UserName != email {
		t.Fatalf("GET user: want %s / %s, got %+v", user.ID, email, got)
	}
	found := scim(http.MethodGet, "/scim/v2/Users?filter="+url.QueryEscape(`userName eq "`+email+`"`), nil, http.StatusOK)
	if found.TotalResults != 1 || len(found.Resources) != 1 || found.Resources[0].ID != user.ID {
		t.Fatalf("filter userName eq: want exactly user %s, got %+v", user.ID, found)
	}

	// The user holds a personal access token and uses it.
	dbPath := filepath.Join(s.Dir, "keyorix.db")
	pat := "kx_pat_" + harness.NewSCIMToken(t)[:43] // 43 URL-safe characters, the shape of a minted token
	seedPAT(t, dbPath, user.ID, pat)
	restExpect(t, s, pat, http.MethodGet, "/api/v1/auth/profile", nil, http.StatusOK)

	// ── 2. deactivation ends the PAT, reactivation does not bring it back ─────────
	off := scim(http.MethodPatch, userPath, scimPatch(map[string]any{"op": "replace", "path": "active", "value": false}), http.StatusOK)
	if off.Active {
		t.Fatalf("PATCH active=false: the user must read back inactive, got %+v", off)
	}
	if gone := restCall(t, s, pat, http.MethodGet, "/api/v1/auth/profile", nil); gone.StatusCode != http.StatusUnauthorized {
		t.Fatalf("a deactivated SCIM user's PAT must stop working at once: want 401, got %d: %s", gone.StatusCode, gone.Raw)
	}
	on := scim(http.MethodPatch, userPath, scimPatch(map[string]any{"op": "replace", "path": "active", "value": true}), http.StatusOK)
	if !on.Active {
		t.Fatalf("PATCH active=true: the user must read back active, got %+v", on)
	}
	if back := restCall(t, s, pat, http.MethodGet, "/api/v1/auth/profile", nil); back.StatusCode != http.StatusUnauthorized {
		t.Fatalf("reactivating the user must not hand the revoked PAT back: want 401, got %d: %s", back.StatusCode, back.Raw)
	}

	// ── 3. group: create, PUT members, PATCH members ──────────────────────────────
	group := scim(http.MethodPost, "/scim/v2/Groups", map[string]any{
		"displayName": "scim-journey-group", "members": []map[string]any{{"value": user.ID}},
	}, http.StatusCreated)
	groupPath := "/scim/v2/Groups/" + group.ID
	wantMembers("create group", group.ID, group, user.ID)

	wantMembers("PUT empty member set", group.ID,
		scim(http.MethodPut, groupPath, map[string]any{"displayName": "scim-journey-group", "members": []map[string]any{}}, http.StatusOK))
	wantMembers("PUT one member", group.ID,
		scim(http.MethodPut, groupPath, map[string]any{
			"displayName": "scim-journey-group", "members": []map[string]any{{"value": user.ID}},
		}, http.StatusOK), user.ID)

	// Removing the only member: 200 with the group, or 204 when only the read-back failed.
	rm := restCall(t, s, s.SCIMToken, http.MethodPatch, groupPath,
		scimPatch(map[string]any{"op": "remove", "path": `members[value eq "` + user.ID + `"]`}))
	if rm.StatusCode != http.StatusOK && rm.StatusCode != http.StatusNoContent {
		t.Fatalf("PATCH remove member: want 200 or 204, got %d: %s", rm.StatusCode, rm.Raw)
	}
	if got := nativeMembers(group.ID); len(got) != 0 {
		t.Fatalf("PATCH remove member: the admin API still lists %v", got)
	}
	wantMembers("PATCH add member", group.ID,
		scim(http.MethodPatch, groupPath, scimPatch(map[string]any{
			"op": "add", "path": "members", "value": []map[string]any{{"value": user.ID}},
		}), http.StatusOK), user.ID)

	// ── 4. deprovision: gone for the IdP and for the admin ────────────────────────
	scim(http.MethodDelete, groupPath, nil, http.StatusNoContent)
	scim(http.MethodGet, groupPath, nil, http.StatusNotFound)
	restExpect(t, s, adminToken, http.MethodGet, "/api/v1/groups/"+group.ID, nil, http.StatusNotFound)
	scim(http.MethodDelete, userPath, nil, http.StatusNoContent)
	scim(http.MethodGet, userPath, nil, http.StatusNotFound)

	// ── 5. audit: the scim.* rows, attributed to the SCIM principal, no token in them ──
	wantRows := map[string]int{
		"scim.user_provisioned":    1,
		"scim.user_updated":        2, // deactivate, reactivate
		"scim.user_deprovisioned":  1,
		"scim.group_provisioned":   1,
		"scim.group_updated":       4, // two PUTs, a PATCH remove, a PATCH add
		"scim.group_deprovisioned": 1,
	}
	for action, want := range wantRows {
		env := restExpect(t, s, adminToken, http.MethodGet, "/api/v1/audit/search?limit=100&action="+url.QueryEscape(action), nil, http.StatusOK)
		var data struct {
			Events []struct {
				EventType   string `json:"event_type"`
				Actor       string `json:"actor"`
				ActorType   string `json:"actor_type"`
				Description string `json:"description"`
			} `json:"events"`
		}
		if err := json.Unmarshal(env.Data, &data); err != nil {
			t.Fatalf("decode audit search for %s: %v\n%s", action, err, env.Raw)
		}
		if len(data.Events) != want {
			t.Fatalf("audit rows %s: want %d, got %d", action, want, len(data.Events))
		}
		for i, e := range data.Events {
			if e.ActorType != "system" || e.Actor != "system" {
				t.Fatalf("audit row %d of %s: want the SCIM principal (actor_type and actor \"system\"), got actor_type %q actor %q",
					i, action, e.ActorType, e.Actor)
			}
			if strings.Contains(e.Description, s.SCIMToken) {
				t.Fatalf("audit row %d of %s contains the SCIM token", i, action)
			}
		}
	}
}

func scimPatch(ops ...map[string]any) map[string]any {
	return map[string]any{
		"schemas":    []string{"urn:ietf:params:scim:api:messages:2.0:PatchOp"},
		"Operations": ops,
	}
}

// seedPAT writes a personal_access_tokens row for userID whose raw token is raw, the way the
// server stores one: only the SHA-256 hex of the token, never the token itself.
func seedPAT(t *testing.T, dbPath, userID, raw string) {
	t.Helper()
	sum := sha256.Sum256([]byte(raw))
	if _, err := strconv.ParseUint(userID, 10, 32); err != nil {
		t.Fatalf("seedPAT: user id %q is not numeric", userID)
	}
	stmt := fmt.Sprintf(
		"INSERT INTO personal_access_tokens (user_id, name, token_hash, token_prefix, revoked, created_at) VALUES (%s, 'scim-journey', '%s', '%s', 0, '%s');",
		userID, hex.EncodeToString(sum[:]), raw[:13], time.Now().UTC().Format("2006-01-02 15:04:05"))
	if out, err := sqliteCLI(dbPath, stmt).CombinedOutput(); err != nil {
		t.Fatalf("seed the user's PAT: %v\n%s", err, out)
	}
}

func sameStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	seen := map[string]int{}
	for _, v := range a {
		seen[v]++
	}
	for _, v := range b {
		seen[v]--
	}
	for _, n := range seen {
		if n != 0 {
			return false
		}
	}
	return true
}
