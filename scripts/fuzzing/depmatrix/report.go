// report.go — generate docs/fuzz/DEP-FUZZ-MATRIX.md and dep-fuzz-matrix.json.
//
// Output is sorted by module path and byte-stable: given the same source tree,
// two runs produce identical files. No timestamps or non-deterministic data are
// included in the JSON (the markdown includes a schema-version line only).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DepRow is one row in the dependency matrix.
type DepRow struct {
	Module      string   `json:"module"`
	Version     string   `json:"version"`
	GoMod       string   `json:"go_mod"`
	ImportCount int      `json:"import_count"`
	TopPkgs     []string `json:"top_pkgs"`
	Reach       string   `json:"reach"`
	Fuzz        string   `json:"fuzz"`
	Evidence    []string `json:"evidence"`
	Notes       string   `json:"notes,omitempty"`
}

// MatrixJSON is the top-level JSON envelope written to dep-fuzz-matrix.json.
type MatrixJSON struct {
	SchemaVersion string     `json:"schema_version"`
	RootModule    string     `json:"root_module"`
	Counts        CountsJSON `json:"counts"`
	Rows          []DepRow   `json:"rows"`
}

// CountsJSON summarises the matrix.
type CountsJSON struct {
	Total         int            `json:"total"`
	ByReach       map[string]int `json:"by_reach"`
	ByFuzz        map[string]int `json:"by_fuzz"`
	UntrustedNone int            `json:"untrusted_none"`
}

// buildCounts builds CountsJSON from a row slice.
func buildCounts(rows []DepRow) CountsJSON {
	c := CountsJSON{
		Total:   len(rows),
		ByReach: map[string]int{},
		ByFuzz:  map[string]int{},
	}
	for _, r := range rows {
		c.ByReach[r.Reach]++
		c.ByFuzz[r.Fuzz]++
		if r.Reach == string(reachUntrusted) && r.Fuzz == string(fuzzNone) {
			c.UntrustedNone++
		}
	}
	return c
}

// writeJSON marshals rows to dep-fuzz-matrix.json at outPath.
// The output is sorted, indented with two spaces, and byte-stable.
func writeJSON(rows []DepRow, rootModule, outPath string) error {
	matrix := MatrixJSON{
		SchemaVersion: "1",
		RootModule:    rootModule,
		Counts:        buildCounts(rows),
		Rows:          rows,
	}
	data, err := json.MarshalIndent(matrix, "", "  ")
	if err != nil {
		return fmt.Errorf("json marshal: %w", err)
	}
	data = append(data, '\n')
	if err := os.MkdirAll(filepath.Dir(outPath), 0o750); err != nil {
		return err
	}
	return os.WriteFile(outPath, data, 0o644) // #nosec G306 -- doc output file
}

// writeMarkdown writes the human-readable matrix to outPath.
func writeMarkdown(rows []DepRow, outPath string) error {
	var buf bytes.Buffer

	counts := buildCounts(rows)

	buf.WriteString("# Dep-Fuzz Matrix\n\n")
	buf.WriteString("<!-- auto-generated by scripts/fuzzing/depmatrix — do not edit by hand -->\n")
	buf.WriteString("<!-- regenerate: go run ./scripts/fuzzing/depmatrix -->\n\n")

	buf.WriteString("## Summary\n\n")
	buf.WriteString("| Metric | Count |\n|--------|-------|\n")
	fmt.Fprintf(&buf, "| Total direct deps | %d |\n", counts.Total)
	fmt.Fprintf(&buf, "| UNTRUSTED | %d |\n", counts.ByReach[string(reachUntrusted)])
	fmt.Fprintf(&buf, "| TRUSTED-ONLY | %d |\n", counts.ByReach[string(reachTrustedOnly)])
	fmt.Fprintf(&buf, "| TOOLING | %d |\n", counts.ByReach[string(reachTooling)])
	fmt.Fprintf(&buf, "| UNUSED | %d |\n", counts.ByReach[string(reachUnused)])
	fmt.Fprintf(&buf, "| FUZZ=DIRECT | %d |\n", counts.ByFuzz[string(fuzzDirect)])
	fmt.Fprintf(&buf, "| FUZZ=WRAPPED | %d |\n", counts.ByFuzz[string(fuzzWrapped)])
	fmt.Fprintf(&buf, "| FUZZ=TARGETS.D | %d |\n", counts.ByFuzz[string(fuzzTargetsD)])
	fmt.Fprintf(&buf, "| FUZZ=NONE | %d |\n", counts.ByFuzz[string(fuzzNone)])
	fmt.Fprintf(&buf, "| **UNTRUSTED+NONE gaps** | **%d** |\n", counts.UntrustedNone)
	buf.WriteString("\n")

	buf.WriteString("## Matrix\n\n")
	buf.WriteString("| Module | Version | go.mod | Importers (N; top 3) | REACH | FUZZ | Evidence | Notes |\n")
	buf.WriteString("|--------|---------|--------|----------------------|-------|------|----------|-------|\n")

	for i := range rows {
		r := &rows[i]
		topStr := strings.Join(r.TopPkgs, "<br>")
		evStr := strings.Join(r.Evidence, "<br>")
		fmt.Fprintf(&buf, "| `%s` | %s | %s | %d; %s | %s | %s | %s | %s |\n",
			r.Module, r.Version, r.GoMod, r.ImportCount, topStr,
			r.Reach, r.Fuzz, evStr, r.Notes)
	}

	buf.WriteString("\n---\n\n")
	buf.WriteString("See [DEP-FUZZ-MATRIX-README.md](DEP-FUZZ-MATRIX-README.md) for class definitions and regeneration instructions.\n")
	buf.WriteString("See [DEP-FUZZ-GAPS.md](DEP-FUZZ-GAPS.md) for the UNTRUSTED+NONE gap analysis.\n")

	if err := os.MkdirAll(filepath.Dir(outPath), 0o750); err != nil {
		return err
	}
	return os.WriteFile(outPath, buf.Bytes(), 0o644) // #nosec G306 -- doc output file
}
