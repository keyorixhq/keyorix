package main

import (
	"fmt"
	"sort"
	"strings"
)

func renderMarkdown(ops []*Op, rows []*CoreRow) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	w("<!-- Code generated by devtools/authzmatrix; DO NOT EDIT. -->\n")
	w("# Cross-layer authz operation matrix\n\n")
	w("Derived by `go run ./devtools/authzmatrix -md server/authzdiff/MATRIX.md -json server/authzdiff/matrix.json`.\n")
	w("Method, population sources and blind spots: the header comment of `devtools/authzmatrix/main.go`.\n\n")
	w("- Mutating = key in `server/faultops` `knownOperations`.\n")
	w("- Secret-reading = reaches, inside core, a `Decrypt*` invoke on an `internal/core/ports` interface, `(*encryption.Service).Decrypt*`, `(*KeyorixCore).decryptVersionValue`, or a `GetSecret` invoke on `ports.Connector`/`connect.Connector`.\n")
	w("- Infra = core method reached by >=10%% of all operations (a shared helper, not an operation); listed separately.\n\n")

	var nRest, nGRPC, inRest, inGRPC int
	for _, op := range ops {
		in := op.Mutating || op.SecretReading
		if op.Layer == "rest" {
			nRest++
			if in {
				inRest++
			}
		} else {
			nGRPC++
			if in {
				inGRPC++
			}
		}
	}
	w("Population: %d REST routes (%d in scope), %d gRPC methods (%d in scope).\n\n", nRest, inRest, nGRPC, inGRPC)

	w("## Operations by core entry point\n\n")
	w("`core refusal`: typed = can return an `ErrPermissionDenied` match; untyped = can return a listed non-matching refusal; none = core does no authz on this path (the transport gate is the only one, so the core-direct leg is not an authz layer for it).\n\n")
	w("| core entry | mut | secret-read | core refusal | named guards reached | REST | gRPC | gap |\n|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		if r.Infra {
			continue
		}
		w("| `%s` | %s | %s | %s | %s | %s | %s | %s |\n", r.Core, yn(r.Mutating), yn(r.SecretReading), r.CoreRefusal,
			strings.Join(r.Guards, ", "), cell(r.REST), cell(r.GRPC), gap(r))
	}

	w("\n## Seed gaps: REST mutating-verb routes absent from faultops knownOperations\n\n")
	for _, op := range ops {
		if op.SeedGap != "" {
			w("- `%s`\n", op.Key)
		}
	}

	w("\n## Infra core methods (excluded from operation rows)\n\n")
	for _, r := range rows {
		if r.Infra {
			w("- `%s` (reached by %d ops)\n", r.Core, r.ReachedBy)
		}
	}

	w("\n## Residue: in-scope operations reaching no non-infra core entry\n\n")
	w("Either raw-storage handlers, handler-only logic, or a resolution miss — each needs a human look.\n\n")
	infra := map[string]bool{}
	for _, r := range rows {
		if r.Infra {
			infra[r.Core] = true
		}
	}
	var res []string
	for _, op := range ops {
		if !(op.Mutating || op.SecretReading) {
			continue
		}
		real := 0
		for _, c := range op.CoreEntries {
			if !infra[c] {
				real++
			}
		}
		if real == 0 || op.Unresolved != "" {
			res = append(res, fmt.Sprintf("- `%s` handler=`%s` raw-storage=%v unresolved=%q", op.Key, op.Handler, op.RawStorage, op.Unresolved))
		}
	}
	sort.Strings(res)
	for _, s := range res {
		w("%s\n", s)
	}

	w("\n## Handlers calling storage directly (raw-storage, outside core)\n\n")
	for _, op := range ops {
		if len(op.RawStorage) > 0 && (op.Mutating || op.SecretReading) {
			w("- `%s`: %s\n", op.Key, strings.Join(op.RawStorage, ", "))
		}
	}
	return b.String()
}

func yn(v bool) string {
	if v {
		return "Y"
	}
	return ""
}

func cell(s []string) string {
	if len(s) == 0 {
		return "—"
	}
	return strings.Join(s, "<br>")
}

func gap(r *CoreRow) string {
	switch {
	case len(r.REST) == 0 && len(r.GRPC) == 0:
		return "core-only"
	case len(r.GRPC) == 0:
		return "no gRPC"
	case len(r.REST) == 0:
		return "no REST"
	}
	return ""
}
