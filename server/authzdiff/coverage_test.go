// Coverage: which in-scope REST operations of the six review families are
// exercised by the harness. Both sides are derived:
//
//   - the population is matrix.json's in-scope ops (mutating or secret-value
//     read) whose route falls in a family, by routeFamily over the PATH;
//   - an op covers a route when the REST request it actually builds (against
//     the template fixtures) matches that route's template.
//
// COVERAGE.md is generated; TestCoverageIsCurrent fails when it is stale.
// Regenerate with: AUTHZDIFF_REGEN_COVERAGE=1 go test ./server/authzdiff -run TestCoverageIsCurrent

var families = []string{"groups", "projects", "machine identities", "invitations", "access requests", "memberships"}

var projSub = regexp.MustCompile(`^/projects/\{[^}]+\}(/[^/]+)?`)

// routeFamily classifies a matrix route path ("/api/v1/...") into a review
// family, or "" when it belongs to none of them.
func routeFamily(path string) string {
	p := strings.TrimPrefix(path, "/api/v1")
	switch {
	case strings.HasPrefix(p, "/groups"):
		return "groups"
	case strings.HasPrefix(p, "/invitations"):
		return "invitations"
	case strings.HasPrefix(p, "/access-requests"):
		return "access requests"
	case p == "/projects":
		return "projects"
	}
	m := projSub.FindStringSubmatch(p)
	if m == nil {
		return ""
	}
	switch m[1] {
	case "", "/restore", "/environments":
		return "projects"
	case "/machine-identities":
		return "machine identities"
	case "/invitations":
		return "invitations"
	case "/access-requests":
		return "access requests"
	case "/memberships", "/members":
		return "memberships"
	}
	return ""
}

type matrixOp struct {
	Key           string `json:"key"`
	Layer         string `json:"layer"`
	Mutating      bool   `json:"mutating"`
	SecretReading bool   `json:"secret_reading"`
}

func familyRoutes(tb testing.TB) map[string][]string {
	b, err := os.ReadFile("matrix.json")
	if err != nil {
		tb.Fatalf("matrix.json: %v", err)
	}
	var m struct {
		Ops []matrixOp `json:"ops"`
	}
	if err := json.Unmarshal(b, &m); err != nil {
		tb.Fatalf("matrix.json: %v", err)
	}
	out := map[string][]string{}
	for _, op := range m.Ops {
		if op.Layer != "rest" || !(op.Mutating || op.SecretReading) {
			continue
		}
		route := strings.TrimPrefix(op.Key, "REST ")
		_, path, _ := strings.Cut(route, " ")
		if f := routeFamily(path); f != "" {
			out[f] = append(out[f], route)
		}
	}
	for f := range out {
		sort.Strings(out[f])
	}
	return out
}

func routeRegexp(route string) *regexp.Regexp {
	method, path, _ := strings.Cut(route, " ")
	re := regexp.QuoteMeta(path)
	re = regexp.MustCompile(`\\\{[^}]+\\\}`).ReplaceAllString(re, `[^/]+`)
	return regexp.MustCompile("^" + method + " " + re + "$")
}

// opRoute returns the matrix route the op's REST request matches, or "".
func opRoute(fx *fixtures, spec opSpec, all []string) string {
	rr := spec.rest(fx, spec.targets[0], 0)
	path, _, _ := strings.Cut(rr.path, "?")
	got := rr.method + " " + path
	for _, r := range all {
		if routeRegexp(r).MatchString(got) {
			return r
		}
	}
	return ""
}

func coverageMarkdown(tb testing.TB) string {
	_, fx := template(tb)
	fr := familyRoutes(tb)
	var all []string
	for _, rs := range fr {
		all = append(all, rs...)
	}
	coveredBy := map[string][]string{}
	for _, spec := range ops() {
		if r := opRoute(fx, spec, all); r != "" {
			coveredBy[r] = append(coveredBy[r], spec.name)
		}
	}
	var b strings.Builder
	b.WriteString("<!-- Code generated by TestCoverageIsCurrent (AUTHZDIFF_REGEN_COVERAGE=1); DO NOT EDIT. -->\n")
	b.WriteString("# authzdiff coverage: in-scope operations of the review families\n\n")
	b.WriteString("Population: `matrix.json` REST ops that are mutating or secret-value reads, classified by route path (`routeFamily`). ")
	b.WriteString("Covered: an op's actual REST request matches the route template.\n\n")
	b.WriteString("| family | in-scope routes | covered | % |\n|---|---|---|---|\n")
	tot, cov := 0, 0
	for _, f := range families {
		n, c := len(fr[f]), 0
		for _, r := range fr[f] {
			if len(coveredBy[r]) > 0 {
				c++
			}
		}
		tot += n
		cov += c
		fmt.Fprintf(&b, "| %s | %d | %d | %d%% |\n", f, n, c, pct(c, n))
	}
	fmt.Fprintf(&b, "| **total** | **%d** | **%d** | **%d%%** |\n\n", tot, cov, pct(cov, tot))
	for _, f := range families {
		fmt.Fprintf(&b, "## %s\n\n", f)
		for _, r := range fr[f] {
			if ops := coveredBy[r]; len(ops) > 0 {
				fmt.Fprintf(&b, "- [x] `%s` — %s\n", r, strings.Join(ops, ", "))
			} else {
				fmt.Fprintf(&b, "- [ ] `%s`\n", r)
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

func pct(a, b int) int {
	if b == 0 {
		return 0
	}
	return a * 100 / b
}

func TestCoverageIsCurrent(t *testing.T) {
	g := guardrules.Rollout(t)
	got := coverageMarkdown(g)
	if os.Getenv("AUTHZDIFF_REGEN_COVERAGE") != "" {
		if err := os.WriteFile("COVERAGE.md", []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile("COVERAGE.md")
	if err != nil || string(want) != got {
		g.Fatalf("COVERAGE.md is stale; regenerate with AUTHZDIFF_REGEN_COVERAGE=1 go test ./server/authzdiff -run TestCoverageIsCurrent")
	}
}

// TestEveryOpBindsAMatrixRoute: an op whose REST request matches no in-scope
// matrix route is either out of scope or mis-built — both must be loud.
// (Secret ops are matched against every REST route, not only family routes.)
func TestEveryOpBindsAMatrixRoute(t *testing.T) {
	_, fx := template(t)
	b, _ := os.ReadFile("matrix.json")
	var m struct {
		Ops []matrixOp `json:"ops"`
	}
	_ = json.Unmarshal(b, &m)
	var all []string
	for _, op := range m.Ops {
		if op.Layer == "rest" {
			all = append(all, strings.TrimPrefix(op.Key, "REST "))
		}
	}
	for _, spec := range ops() {
		if opRoute(fx, spec, all) == "" {
			t.Errorf("op %s: its REST request matches no matrix route", spec.name)
		}
	}
}

// familyOrder sorts ops by review family (then name), for the sweep.
func familyOrder(tb testing.TB, specs []opSpec) []opSpec {
	_, fx := template(tb)
	fr := familyRoutes(tb)
	idx := map[string]int{}
	for i, f := range families {
		for _, r := range fr[f] {
			idx[r] = i + 1
		}
	}
	var all []string
	for _, rs := range fr {
		all = append(all, rs...)
	}
	rank := func(s opSpec) int { return idx[opRoute(fx, s, all)] } // 0 = secret ops first
	out := slices.Clone(specs)
	sort.SliceStable(out, func(i, j int) bool { return rank(out[i]) < rank(out[j]) })
	return out
}
