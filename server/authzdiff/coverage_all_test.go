// Coverage over EVERY in-scope operation in matrix.json (REST and gRPC), not
// only the six review families. Covered is derived on both transports:
//
//   - REST: the op's actual request matches the route template (opRoute);
//   - gRPC: the RPC the op's gRPC leg actually calls, recorded by the leg's
//     client interceptor (recordRPC) while the op runs as the admin.
//
// Every in-scope operation that is NOT covered must carry a reason in
// uncoveredReasons (or its family default); TestCoverageAllIsCurrent fails on
// one that does not, so the "why not" list cannot silently go stale.
// Regenerate: AUTHZDIFF_REGEN_COVERAGE=1 go test ./server/authzdiff -run TestCoverageAllIsCurrent

var allFamilies = append(append([]string{}, families...), "secrets", "other")

// opFamily classifies any in-scope matrix op key.
func opFamily(key string) string {
	if strings.HasPrefix(key, "GRPC ") {
		svc := strings.TrimPrefix(key, "GRPC keyorix.v1.")
		svc, _, _ = strings.Cut(svc, ".")
		switch svc {
		case "GroupService":
			return "groups"
		case "ProjectService":
			return "projects"
		case "MachineIdentityService":
			return "machine identities"
		case "SecretService", "ShareService":
			return "secrets"
		}
		return "other"
	}
	_, path, _ := strings.Cut(strings.TrimPrefix(key, "REST "), " ")
	if f := routeFamily(path); f != "" {
		return f
	}
	p := strings.TrimPrefix(path, "/api/v1")
	if strings.HasPrefix(p, "/secrets") || strings.HasPrefix(p, "/shares") || strings.HasPrefix(p, "/secret-access-requests") ||
		strings.Contains(p, "/secrets/") || strings.HasSuffix(p, "/secrets") {
		return "secrets"
	}
	return "other"
}

func inScopeOps(tb testing.TB) []matrixOp {
	b, err := os.ReadFile("matrix.json")
	if err != nil {
		tb.Fatalf("matrix.json: %v", err)
	}
	var m struct {
		Ops []matrixOp `json:"ops"`
	}
	if err := json.Unmarshal(b, &m); err != nil {
		tb.Fatalf("matrix.json: %v", err)
	}
	var out []matrixOp
	for _, op := range m.Ops {
		if op.Mutating || op.SecretReading {
			out = append(out, op)
		}
	}
	return out
}

// coveredKeys derives the covered matrix keys ("REST ..." / "GRPC ...") and
// which harness op covers each.
func coveredKeys(tb testing.TB) map[string][]string {
	_, fx := template(tb)
	out := map[string][]string{}
	var restRoutes []string
	for _, op := range inScopeOps(tb) {
		if op.Layer == "rest" {
			restRoutes = append(restRoutes, strings.TrimPrefix(op.Key, "REST "))
		}
	}
	// One gRPC leg serves every probe: only WHICH RPC an op calls is recorded,
	// and every op's gRPC leg makes its call whatever the database state.
	lg := newLeg(tb, layerGRPC)
	defer lg.close()
	for _, spec := range withDerived(tb, ops()) {
		if r := opRoute(fx, spec, restRoutes); r != "" {
			out["REST "+r] = append(out["REST "+r], spec.name)
		}
		if spec.grpc == nil {
			continue
		}
		for _, t := range spec.targets {
			var seen []string
			rpcRecorderMu.Lock()
			rpcRecorder = func(m string) { seen = append(seen, m) }
			rpcRecorderMu.Unlock()
			err := spec.grpc(grpcCtx(fx.principals[pkGlobalAdmin]), lg, t, 0)
			rpcRecorderMu.Lock()
			rpcRecorder = nil
			rpcRecorderMu.Unlock()
			if errors.Is(err, errLayerAbsent) {
				continue // this target is not expressible on gRPC; try the next
			}
			for _, m := range seen {
				key := "GRPC " + strings.Replace(strings.TrimPrefix(m, "/"), "/", ".", 1)
				if !slices.Contains(out[key], spec.name) {
					out[key] = append(out[key], spec.name)
				}
			}
			break // the RPC an op calls does not depend on the target
		}
	}
	return out
}

func coverageAllMarkdown(tb testing.TB) (string, []string) {
	cov := coveredKeys(tb)
	byFam := map[string][]matrixOp{}
	for _, op := range inScopeOps(tb) {
		f := opFamily(op.Key)
		byFam[f] = append(byFam[f], op)
	}
	var missing []string
	var b strings.Builder
	b.WriteString("<!-- Code generated by TestCoverageAllIsCurrent (AUTHZDIFF_REGEN_COVERAGE=1); DO NOT EDIT. -->\n")
	b.WriteString("# authzdiff coverage: every in-scope operation in matrix.json\n\n")
	b.WriteString("In scope = mutating or secret-value read (`matrix.json`). Covered = derived: REST by request/route-template match, ")
	b.WriteString("gRPC by the RPC the op's gRPC leg actually calls (client interceptor). Every uncovered op carries a reason.\n\n")
	b.WriteString("| family | REST in scope | REST covered | gRPC in scope | gRPC covered |\n|---|---|---|---|---|\n")
	var tr, cr, tg, cg int
	for _, f := range allFamilies {
		var r, rc, g, gc int
		for _, op := range byFam[f] {
			c := len(cov[op.Key]) > 0
			if op.Layer == "rest" {
				r++
				if c {
					rc++
				}
			} else {
				g++
				if c {
					gc++
				}
			}
		}
		tr, cr, tg, cg = tr+r, cr+rc, tg+g, cg+gc
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d |\n", f, r, rc, g, gc)
	}
	fmt.Fprintf(&b, "| **total** | **%d** | **%d** | **%d** | **%d** |\n\n", tr, cr, tg, cg)
	for _, f := range allFamilies {
		ops := byFam[f]
		sort.Slice(ops, func(i, j int) bool { return ops[i].Key < ops[j].Key })
		fmt.Fprintf(&b, "## %s\n\n", f)
		for _, op := range ops {
			if by := cov[op.Key]; len(by) > 0 {
				fmt.Fprintf(&b, "- [x] `%s` — %s\n", op.Key, strings.Join(by, ", "))
				continue
			}
			reason := uncoveredReason(op.Key, f)
			if reason == "" {
				missing = append(missing, op.Key)
				reason = "UNCLASSIFIED"
			}
			fmt.Fprintf(&b, "- [ ] `%s` — %s\n", op.Key, reason)
		}
		b.WriteString("\n")
	}
	return b.String(), missing
}

func TestCoverageAllIsCurrent(t *testing.T) {
	got, missing := coverageAllMarkdown(t)
	if os.Getenv("AUTHZDIFF_REGEN_COVERAGE") != "" {
		if err := os.WriteFile("COVERAGE-ALL.md", []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
	} else if want, err := os.ReadFile("COVERAGE-ALL.md"); err != nil || string(want) != got {
		t.Fatalf("COVERAGE-ALL.md is stale; regenerate with AUTHZDIFF_REGEN_COVERAGE=1 go test ./server/authzdiff -run TestCoverageAllIsCurrent")
	}
	for _, k := range missing {
		t.Errorf("in-scope operation %s is neither covered nor given a reason in uncoveredReasons", k)
	}
}
